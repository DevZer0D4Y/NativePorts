#!/usr/bin/env python3
"""Generate both native shader backends from one math source."""
from pathlib import Path
import re
r=Path(__file__).resolve().parents[1]
math=(r/'shared/newpixie.glsl').read_text()
gl='''#version 120
uniform sampler2D sourceTex,feedbackTex,blurTex;
uniform vec2 sourceSize,outputSize;
uniform float frame;
uniform int mode;
varying vec2 uv;
'''+math+'''
void main() {
 if(mode==1) gl_FragColor=max(texture2D(feedbackTex,uv)*0.65,texture2D(sourceTex,uv)*0.96);
 else if(mode==2) gl_FragColor=blur9(sourceTex,uv,vec2(1.0/sourceSize.x,0));
 else if(mode==3) gl_FragColor=blur9(sourceTex,uv,vec2(0,1.0/sourceSize.y));
 else if(mode==4) gl_FragColor=newpixie(sourceTex,blurTex,uv,outputSize,frame);
 else gl_FragColor=texture2D(sourceTex,uv);
}
'''
metal=re.sub(r'\bvec([234])\b',r'float\1',math).replace('sampler2D','texture2d<float>').replace('texture2D(','sampleTex(').replace('mod(','fmod(')
metal='''#include <metal_stdlib>
using namespace metal;
float4 sampleTex(texture2d<float> tex, float2 uv) {
 constexpr sampler s(coord::normalized, address::clamp_to_edge, filter::linear);
 return tex.sample(s,uv);
}
struct V { float4 position [[position]]; float2 uv; };
vertex V crtVertex(uint id [[vertex_id]]) {
 float2 p=float2((id<<1)&2,id&2);
 V v;v.position=float4(p*float2(2,-2)+float2(-1,1),0,1);v.uv=p;return v;
}
struct Params { float2 sourceSize;float2 outputSize;float frame;int mode; };
'''+metal+'''
fragment float4 crtFragment(V v [[stage_in]], texture2d<float> src [[texture(0)]],
 texture2d<float> feedback [[texture(1)]],texture2d<float> blur [[texture(2)]],constant Params &p [[buffer(0)]]) {
 if(p.mode==1) return max(sampleTex(feedback,v.uv)*0.65,sampleTex(src,v.uv)*0.96);
 if(p.mode==2) return blur9(src,v.uv,float2(1.0/p.sourceSize.x,0));
 if(p.mode==3) return blur9(src,v.uv,float2(0,1.0/p.sourceSize.y));
 if(p.mode==4) return newpixie(src,blur,v.uv,p.outputSize,p.frame);
 return sampleTex(src,v.uv);
}
'''
metal=metal.replace(' return sampleTex(src,v.uv);',' if(p.mode==5)return sampleTex(src,v.uv);\n constexpr sampler nearestSampler(coord::normalized,address::clamp_to_edge,filter::nearest);\n return src.sample(nearestSampler,v.uv);')
def c_string(s):return '"'+s.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n"\n"')+'"'
header=('/* Generated by scripts/generate_shaders.py */\nstatic const char *crt_fragment='+c_string(gl)+';\nstatic const char *crt_vertex='+c_string('#version 120\nvarying vec2 uv;void main(){gl_Position=gl_Vertex;uv=gl_MultiTexCoord0.xy;}')+';\n')

for port in (r/"ports").iterdir():
 (port/"desktop/Shaders.h").write_text(header)
 (port/"ios/Hangtime/NewPixie.metal").write_text(metal)
